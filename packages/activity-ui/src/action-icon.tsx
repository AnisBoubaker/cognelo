export type ActionIconName = keyof typeof actionIcons;

/** Decorative semantic icons: the action label supplies the accessible name. */
export function ActionIcon({ name, size = 18, stroke = 2 }: { name: ActionIconName; size?: number; stroke?: number }) {
  const Icon = actionIcons[name];
  return <Icon aria-hidden="true" focusable="false" data-action-icon={name} size={size} stroke={stroke} />;
}
