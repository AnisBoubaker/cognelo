import { prisma } from "@cognelo/db";
import { test, expect } from "./fixtures/bank-course";
import { createCourseActivity, responseJson } from "./fixtures/activity-suite";
import { ensureContentTypePluginEnabled } from "./fixtures/content-plugins";
import { homeworkModelFixture } from "./fixtures/homework-model";
import { createAuthenticatedApi } from "./fixtures/auth";

test("teacher simulation uses the real French question rules, supports cancellation, and creates no student records", async ({ bankCourse: data, teacherApi, browser }) => {
  test.setTimeout(150_000);
  await ensureContentTypePluginEnabled("text-content");
  await prisma.subject.update({ where: { id: data.subjectId }, data: { teachingLanguage: "fr" } });
  const model = await homeworkModelFixture(data, { hold: true, questionText: number => `Dans solution_add, pourquoi la condition protège-t-elle ce cas ${number} ? Expliquez en quelques phrases.` });
  const api = model.api, page = await model.page(browser), student = await createAuthenticatedApi("student"); let activityId: string | undefined;
  try {
    const course = `/api/courses/${data.courseId}`;
    const { resource } = await responseJson<{ resource: { id: string } }>(await api.post(`${course}/content-resources`, { data: { contentTypeKey: "text", payload: { title: "Reference for simulation", body: "PRIVATE_REFERENCE: C guards can handle boundary values before returning a sum." }, isVisible: false } }));
    activityId = await createCourseActivity(data, { activityTypeKey: "coding-homework-grader", title: "Private teacher simulation", config: {} });
    const base = `${course}/activities/${activityId}/coding-homework-grader`, references = `${course}/activities/${activityId}/material-references`;
    const current = await responseJson<{ assignment: object }>(await api.get(`${base}/authoring`));
    await responseJson(await api.put(`${base}/authoring`, { data: { assignment: { ...current.assignment, questionCount: 3, generationInstructions: "Focus on one guard and its return value." }, requirements: {} } }));
    const helper = "int provided_helper(int x) { return x + 1; }";
    const solution = `${helper}\nint solution_add(int left, int right) { if (left < 0) return right; return left + right; }`;
    await responseJson(await api.post(`${base}/provided-files`, { data: { fileName: "starter.c", base64: Buffer.from(helper).toString("base64") } }));
    await responseJson(await api.put(`${base}/teacher-solution`, { data: { fileName: "solution.c", base64: Buffer.from(solution).toString("base64") } }));
    await responseJson(await api.put(references, { data: { selected: [resource.id] } }));
    expect((await api.post(`${base}/simulation`, { data: {} })).status()).toBe(409);
    await responseJson(await api.post(`${references}/prepare-material`, { data: { resourceId: resource.id } }));
    await responseJson(await api.post(`${references}/prepare`, { data: {} }));
    expect((await student.post(`${base}/simulation`, { data: {} })).status()).toBe(403);
    const counts = async () => ({ attempts: await prisma.activityAttempt.count({ where: { activityId } }), submissions: (await prisma.$queryRaw<Array<{ count: bigint }>>`SELECT count(*) FROM "PluginCodingHomeworkSubmission" WHERE "activityId"=${activityId}`)[0].count.toString() });
    expect(await counts()).toEqual({ attempts: 0, submissions: "0" });
    await page.goto(`/courses/${data.courseId}/activities/${activityId}`);
    await page.getByRole("tab", { name: "Simulation", exact: true }).click();
    const simulation = page.locator(".homework-simulation"), generate = simulation.getByRole("button", { name: "Generate simulation questions", exact: true });
    await expect(generate).toBeEnabled(); await generate.click();
    const progress = page.getByRole("dialog", { name: "Generating simulation questions…", exact: true });
    await expect(progress).toBeVisible(); await expect.poll(() => model.active).toBe(1);
    await progress.getByRole("button", { name: "Cancel", exact: true }).click();
    await expect(progress).toBeHidden(); model.release();
    await expect(simulation.locator(".homework-challenge-question")).toHaveCount(0);
    await expect.poll(() => model.active).toBe(0); expect(model.starts).toHaveLength(1);
    await generate.click(); await expect(progress).toBeVisible(); await expect(progress).toBeHidden({ timeout: 45_000 });
    await expect(simulation.locator(".homework-challenge-question")).toHaveCount(3);
    await expect(simulation).toContainText("Dans solution_add");
    await expect(simulation.getByRole("region", { name: "Teacher solution in context", exact: true })).toHaveCount(3);
    await expect(simulation.locator("textarea")).toHaveCount(0);
    await expect(simulation).not.toContainText("PRIVATE_REFERENCE");
    const generation = model.requests.filter(request => request.userPrompt?.includes("submittedCode"));
    expect(generation.length).toBeGreaterThanOrEqual(3);
    for (const request of generation) {
      expect(request.systemPrompt).toContain("COURSE TEACHING LANGUAGE: French"); expect(request.systemPrompt).toContain("Focus on one guard and its return value.");
      expect(JSON.parse(request.userPrompt!).submittedFunction).toBe("solution_add");
      expect(JSON.parse(request.userPrompt!).privateReferenceContext[0].text).toContain("PRIVATE_REFERENCE");
    }
    expect(await counts()).toEqual({ attempts: 0, submissions: "0" });
    await page.screenshot({ path: "tmp/homework-simulation.png", fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
    await simulation.screenshot({ path: "tmp/homework-simulation-mobile.png" });
    await page.setViewportSize({ width: 1280, height: 800 });
    await page.getByRole("tab", { name: "Activity", exact: true }).click(); await page.getByRole("tab", { name: "Simulation", exact: true }).click();
    await expect(simulation.locator(".homework-challenge-question")).toHaveCount(3);
    await page.getByRole("tab", { name: "Settings", exact: true }).click();
    await page.getByLabel("AI question-generation instructions", { exact: true }).fill("Unsaved simulation instructions.");
    await page.getByRole("tab", { name: "Simulation", exact: true }).click(); await expect(generate).toBeDisabled();
    await expect(simulation).toContainText("Save activity and reference changes");
    await page.getByRole("tab", { name: "Settings", exact: true }).click();
    await page.locator(".homework-workflow-settings .edit-action-bar").first().getByRole("button", { name: "Cancel", exact: true }).click();
    await page.getByRole("tab", { name: "Simulation", exact: true }).click(); await expect(generate).toBeEnabled();
    await page.getByRole("tab", { name: "Settings", exact: true }).click();
    const settings = page.locator(".homework-workflow-settings");
    await settings.getByLabel("AI connection", { exact: true }).selectOption(model.connection.id);
    await page.getByRole("tab", { name: "Simulation", exact: true }).click(); await expect(generate).toBeDisabled();
    await page.getByRole("tab", { name: "Settings", exact: true }).click();
    await settings.getByRole("button", { name: "Save model choice", exact: true }).click();
    await page.getByRole("tab", { name: "Simulation", exact: true }).click(); await expect(generate).toBeEnabled();
    await responseJson(await teacherApi.post(`${course}/groups/${data.groupId}/activities`, { data: { activityId, metadata: { assessmentMode: "summative" } } }));
    await responseJson(await api.put(`${base}/workflow-settings`, { data: { enabled: true } }));
    const learner = `${course}/groups/${data.groupId}/activities/assigned/${activityId}/coding-homework-grader`;
    expect((await student.post(`${learner}/simulation`, { data: {} })).status()).toBe(403);
    await responseJson(await student.post(`${learner}/preparation`, { data: { kind: "file", path: "solution.c", expectedRevision: 0, base64: Buffer.from(solution).toString("base64") } }));
    await responseJson(await student.post(`${learner}/hand-in`, { data: { expectedRevision: 1 } }));
    await expect.poll(async () => (await responseJson<{ submission: { status: string } }>(await student.get(`${learner}/workspace`))).submission.status, { timeout: 45_000 }).toBe("challenge_ready");
    const last = model.requests.filter(request => request.userPrompt?.includes("submittedCode")).slice(-3);
    expect(last.every(request => JSON.parse(request.userPrompt!).submittedFunction === "solution_add")).toBe(true);
    expect(await counts()).toEqual({ attempts: 0, submissions: "1" });
  } finally {
    model.release();
    if (activityId) await prisma.backgroundJob.deleteMany({ where: { payload: { path: ["activityId"], equals: activityId } } });
    await page.close(); await student.dispose(); await model.close();
  }
});
