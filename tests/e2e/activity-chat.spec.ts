test("retained history is paginated and scoped to its student and attempt", async ({ bankCourse: data, teacherApi }) => {
  const studentApi = await createAuthenticatedApi("student");
  const assigned = `/api/courses/${data.courseId}/groups/${data.groupId}/activities/assigned/${data.activityId}`;
  const messages = `/api/courses/${data.courseId}/gradebook/activities/${data.activityId}/messages`;
  try {
    const path = `${data.courseActivityPath}/assign-all-groups`;
    const { settings } = await responseJson<{ settings: CourseActivityAssignmentSettings }>(await teacherApi.get(path));
    await responseJson(await teacherApi.post(path, { data: { ...settings.general, assessmentMode: "summative", messagingEnabled: true, twoWayMessagingEnabled: true, groupAssignments: settings.groups } }));
    const { conversation } = await responseJson<{ conversation: LearnerActivityConversation }>(await studentApi.get(`${assigned}/messages`));
    const identity = await prisma.activityConversation.findUniqueOrThrow({ where: { id: conversation.id } });
    const sender = await prisma.user.findUniqueOrThrow({ where: { email: "teacher@cognelo.local" } });
    const start = Date.now() - 200_000;
    await prisma.activityConversationMessage.createMany({ data: Array.from({ length: 105 }, (_, index) => ({
      conversationId: conversation.id, senderUserId: sender.id, senderKind: "staff" as const, senderName: "Teacher", body: `Archived message ${index}`, createdAt: new Date(start + index * 1000)
    })) });
    const first = await responseJson<{ conversation: LearnerActivityConversation }>(await studentApi.get(`${assigned}/messages`));
    expect(first.conversation.hasMore).toBe(true);
    expect(first.conversation.messages).toHaveLength(100);
    const earlier = await responseJson<{ conversation: LearnerActivityConversation }>(await studentApi.get(`${assigned}/messages?before=${first.conversation.messages[0].id}`));
    expect(earlier.conversation.hasMore).toBe(false);
    expect(earlier.conversation.messages.map((message) => message.body)).toEqual(Array.from({ length: 5 }, (_, index) => `Archived message ${index}`));
    const staff = await responseJson<{ conversation: StaffActivityConversation }>(await teacherApi.get(`${messages}/conversations/${identity.participantId}`));
    expect(staff.conversation.canSend).toBe(false); // No student-initiated conversation.
    expect(staff.conversation.hasMore).toBe(true);
    expect((await studentApi.get(`${assigned}/messages?before=not-owned`)).status()).toBe(404);
    expect((await teacherApi.get(`${messages}/conversations/${identity.participantId}?attemptId=not-owned`)).status()).toBe(404);
    await responseJson(await studentApi.patch(`${assigned}/messages`, { data: { conversationId: conversation.id, lastMessageId: first.conversation.messages.at(-1)!.id } }));
    expect((await responseJson<{ conversation: LearnerActivityConversation }>(await studentApi.get(`${assigned}/messages`))).conversation.unreadCount).toBe(0);
    await responseJson(await studentApi.patch(`${assigned}/messages`, { data: { conversationId: conversation.id, lastMessageId: earlier.conversation.messages[0].id } }));
    expect((await responseJson<{ conversation: LearnerActivityConversation }>(await studentApi.get(`${assigned}/messages`))).conversation.unreadCount).toBe(0);
  } finally { await studentApi.dispose(); }
});

test("messaging uses the existing activity heartbeat and fetches history only on changes", async ({ bankCourse: data, teacherApi, studentPage, teacherPage }) => {
  test.setTimeout(180_000);
  const assigned = `/api/courses/${data.courseId}/groups/${data.groupId}/activities/assigned/${data.activityId}`;
  const staffMessages = `/api/courses/${data.courseId}/gradebook/activities/${data.activityId}/messages`;
  const settingsPath = `${data.courseActivityPath}/assign-all-groups`;
  const { settings } = await responseJson<{ settings: CourseActivityAssignmentSettings }>(await teacherApi.get(settingsPath));
  await responseJson(await teacherApi.post(settingsPath, { data: { ...settings.general, assessmentMode: "summative", messagingEnabled: true, groupAssignments: settings.groups } }));
  let learnerHistoryRequests = 0;
  let teacherHistoryRequests = 0;
  let teacherStatusRequests = 0;
  studentPage.on("request", (request) => { if (request.method() === "GET" && new URL(request.url()).pathname === `${assigned}/messages`) learnerHistoryRequests++; });
  teacherPage.on("request", (request) => {
    const url = new URL(request.url());
    if (request.method() !== "GET" || url.pathname !== staffMessages) return;
    if (url.searchParams.get("summary") === "1") teacherStatusRequests++; else teacherHistoryRequests++;
  });
  await studentPage.goto(assigned.replace("/api", ""));
  await expect(studentPage.getByRole("button", { name: "Open activity messages", exact: true })).toBeVisible({ timeout: 30_000 });
  const heartbeat = () => studentPage.waitForResponse((response) => new URL(response.url()).pathname === `${assigned}/content-access` && response.request().method() === "GET", { timeout: 30_000 });
  const firstPoll = await heartbeat();
  const payload = await firstPoll.json();
  expect(payload.messaging).toEqual(expect.objectContaining({ version: expect.any(String), unreadCount: 0 }));
  expect(payload.messaging).not.toHaveProperty("messages");
  expect(learnerHistoryRequests).toBe(0);
  await studentPage.getByRole("button", { name: "Open activity messages", exact: true }).click();
  await expect(studentPage.getByRole("dialog", { name: "Activity messages" }).getByText("No messages yet.")).toBeVisible();
  expect(learnerHistoryRequests).toBe(1);
  await heartbeat();
  expect(learnerHistoryRequests).toBe(1);
  await responseJson(await teacherApi.post(staffMessages, { data: { body: "Only fetch this when the revision changes." } }));
  await expect(studentPage.getByRole("dialog", { name: "Activity messages" }).getByText("Only fetch this when the revision changes.")).toBeVisible({ timeout: 30_000 });
  expect(learnerHistoryRequests).toBe(2);
  await teacherPage.goto(`/courses/${data.courseId}/gradebook/activities/${data.activityId}`);
  await teacherPage.getByRole("button", { name: "Message students", exact: true }).click();
  await expect(teacherPage.getByRole("dialog", { name: "Activity messages" }).getByText("Only fetch this when the revision changes.")).toBeVisible();
  const status = await teacherPage.waitForResponse((response) => new URL(response.url()).pathname === staffMessages && new URL(response.url()).searchParams.get("summary") === "1", { timeout: 15_000 });
  expect((await status.json()).messaging).not.toHaveProperty("broadcasts");
  const historyCount = teacherHistoryRequests;
  await teacherPage.waitForResponse((response) => new URL(response.url()).pathname === staffMessages && new URL(response.url()).searchParams.get("summary") === "1", { timeout: 15_000 });
  expect(teacherHistoryRequests).toBe(historyCount);
  await teacherPage.getByRole("dialog", { name: "Activity messages" }).getByRole("button", { name: "Close", exact: true }).click();
  await teacherPage.goto("/courses");
  const requestsAfterLeaving = teacherStatusRequests;
  await studentPage.getByRole("dialog", { name: "Activity messages" }).getByRole("button", { name: "Close", exact: true }).click();
  await heartbeat();
  expect(teacherStatusRequests).toBe(requestsAfterLeaving);
  expect(learnerHistoryRequests).toBe(2);
});
