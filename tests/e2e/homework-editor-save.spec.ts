import { test, expect } from "./fixtures/bank-course";
import { createCourseActivity, responseJson } from "./fixtures/activity-suite";
import { homeworkModelFixture } from "./fixtures/homework-model";
import { openHomeworkEditorSection } from "./fixtures/homework-editor";
import type { CodingHomeworkAuthoringRecord } from "../../packages/plugin-activities/plugin-coding-homework-grader/src/web/client";

test("one homework Save/Cancel covers activity-specific left sections and persists the combined draft", async ({ bankCourse: data, browser }) => {
  test.setTimeout(120_000);
  const model = await homeworkModelFixture(data), page = await model.page(browser), api = model.api;
  try {
    await responseJson(await api.patch(`/api/ai-agents/${model.connection.id}`, { data: { models: [{ model: "synthetic-model", purpose: "generation" }, { model: "alternate-text", purpose: "generation" }] } }));
    const id = await createCourseActivity(data, { activityTypeKey: "coding-homework-grader", title: "One homework draft", config: {} });
    const base = `/api/courses/${data.courseId}/activities/${id}/coding-homework-grader`;
    const initial = await responseJson<CodingHomeworkAuthoringRecord>(await api.get(`${base}/authoring`));
    await responseJson(await api.put(`${base}/authoring`, { data: { assignment: initial.assignment, requirements: initial.requirements.requirements } }));
    await page.goto(`/courses/${data.courseId}/activities/${id}`);
    const bar = page.locator(".homework-authoring-panel > form > div > .edit-action-bar");
    const snapshot = async () => responseJson<CodingHomeworkAuthoringRecord>(await api.get(`${base}/authoring`));
    const before = await snapshot();
    const mutations: string[] = [];
    page.on("request", request => { if (request.method() === "PUT" && request.url().includes(base)) mutations.push(request.url()); });
    const edit = async () => {
      await openHomeworkEditorSection(page, "Submission requirements");
      await page.getByLabel("Required files", { exact: true }).fill("main.c");
      await openHomeworkEditorSection(page, "Question Generation");
      await expect(page.getByRole("button", { name: "Save", exact: true })).toHaveCount(1);
      await expect(page.getByRole("button", { name: "Save model choice", exact: true })).toHaveCount(0);
      await page.locator(".homework-workflow-questions").getByLabel("AI connection", { exact: true }).selectOption(model.connection.id);
      await page.locator(".homework-workflow-questions").getByLabel("Model", { exact: true }).selectOption("alternate-text");
      await page.getByLabel("Students processed at once (1–4)").fill("3");
      await page.getByLabel("AI question-generation instructions", { exact: true }).fill("Ask about one guard.");
      await openHomeworkEditorSection(page, "Submission settings");
      await expect(page.getByRole("button", { name: "Save", exact: true })).toHaveCount(1);
      await expect(page.getByRole("button", { name: "Save deadline settings", exact: true })).toHaveCount(0);
      await page.getByLabel("Max files", { exact: true }).fill("90");
    };
    await edit();
    await page.evaluate(() => window.dispatchEvent(new Event("focus")));
    await expect(bar).toContainText("You have unsaved changes.");
    expect(mutations).toEqual([]); expect(await snapshot()).toEqual(before);
    await bar.getByRole("button", { name: "Cancel", exact: true }).click();
    await expect(page.getByLabel("Max files", { exact: true })).toHaveValue("200");
    await openHomeworkEditorSection(page, "Question Generation");
    await expect(page.getByLabel("Students processed at once (1–4)")).toHaveValue("2");
    await expect(page.getByLabel("AI question-generation instructions", { exact: true })).toHaveValue("");
    await expect(page.locator(".homework-workflow-questions").getByLabel("AI connection", { exact: true })).toHaveValue("");
    await openHomeworkEditorSection(page, "Submission requirements");
    await expect(page.getByLabel("Required files", { exact: true })).toHaveValue("");
    expect(mutations).toEqual([]);
    await edit();
    const saved = page.waitForResponse(response => response.url().endsWith(`${base}/authoring`) && response.request().method() === "PUT");
    await bar.getByRole("button", { name: "Save", exact: true }).click();
    expect((await saved).ok()).toBe(true); await expect(bar).toContainText("Everything is saved.");
    expect(mutations).toHaveLength(1); expect(mutations[0]).toContain("/authoring");
    const authored = await snapshot();
    expect(authored).toMatchObject({ assignment: { generationInstructions: "Ask about one guard.", settings: { generationConcurrency: 3, questionGenerationAi: { connectionId: model.connection.id, model: "alternate-text" } } }, requirements: { requirements: { maxFileCount: 90, requiredFiles: [{ path: "main.c" }] } } });
    await page.reload(); await openHomeworkEditorSection(page, "Submission settings");
    await expect(page.getByLabel("Max files", { exact: true })).toHaveValue("90");
    await openHomeworkEditorSection(page, "Question Generation");
    await expect(page.locator(".homework-workflow-questions").getByLabel("Model", { exact: true })).toHaveValue("alternate-text");
    await expect(page.getByLabel("Students processed at once (1–4)")).toHaveValue("3");
    await page.screenshot({ path: "tmp/homework-one-save-questions.png", fullPage: true });
  } finally { await page.close(); await model.close(); }
});
